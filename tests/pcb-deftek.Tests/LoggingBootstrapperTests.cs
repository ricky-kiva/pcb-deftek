using System;
using System.IO;
using System.Linq;
using FluentAssertions;
using pcb_deftek.Infrastructure.Logging;
using Serilog;
using Xunit;

namespace pcb_deftek.Tests;

public class LoggingBootstrapperTests
{
    [Fact]
    public void GetDefaultLogDirectory_WhenCalled_ReturnsLocalAppDataPcbDeftekDirectory()
    {
        // Act
        string logDir = LoggingBootstrapper.GetDefaultLogDirectory();

        // Assert
        logDir.Should().NotBeNullOrWhiteSpace();
        logDir.Should().Contain("PcbDeftek");
        logDir.Should().Contain("logs");
    }

    [Fact]
    public void GetDefaultLogFilePath_WhenCalled_EndsWithDailyRollingPattern()
    {
        // Act
        string logFilePath = LoggingBootstrapper.GetDefaultLogFilePath();

        // Assert
        logFilePath.Should().EndWith("app-.log");
    }

    [Fact]
    public void Initialize_WithCustomDirectory_CreatesLogFileAndWritesFormattedEntries()
    {
        // Arrange
        string tempDir = Path.Combine(Path.GetTempPath(), "pcb-deftek-tests-" + Guid.NewGuid().ToString("N"));

        try
        {
            // Act
            LoggingBootstrapper.Initialize(tempDir);
            Log.Information("TDD verification test message {TestId}", 9999);
            LoggingBootstrapper.Shutdown();

            // Assert
            Directory.Exists(tempDir).Should().BeTrue("Directory must be created if absent");
            var logFiles = Directory.GetFiles(tempDir, "app-*.log");
            logFiles.Should().NotBeEmpty("Rolling log file should be generated by Serilog");

            string content = File.ReadAllText(logFiles.First());
            content.Should().Contain("[INF]");
            content.Should().Contain("TDD verification test message 9999");
        }
        finally
        {
            LoggingBootstrapper.Shutdown();
            if (Directory.Exists(tempDir))
            {
                try { Directory.Delete(tempDir, recursive: true); } catch { /* ignore filesystem lock */ }
            }
        }
    }

    [Fact]
    public void Shutdown_WhenCalledMultipleTimes_ExecutesWithoutException()
    {
        // Act
        Action act = () =>
        {
            LoggingBootstrapper.Shutdown();
            LoggingBootstrapper.Shutdown();
        };

        // Assert
        act.Should().NotThrow("Multiple shutdown calls should be idempotent");
    }
}
